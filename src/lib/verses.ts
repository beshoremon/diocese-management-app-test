/** Deterministic verse for a 'YYYY-MM-DD' day. */
export function verseOfDay(ymd: string): Verse {
  const [y, m, d] = ymd.split('-').map(Number);
  const dayOfYear = Math.floor((Date.UTC(y, m - 1, d) - Date.UTC(y, 0, 1)) / 86_400_000);
  return VERSES[(dayOfYear + y) % VERSES.length];
}
