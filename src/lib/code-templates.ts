// ---------- normalize (never trust stored JSON) ----------
const DATE_FORMATS: DateFormat[] = ['YYYYMMDD', 'YYMMDD', 'DDMMYYYY', 'DDMMYY', 'YYYYMM', 'YYMM', 'YYYY', 'YY'];
const CHARSET_KEYS: RandomCharset[] = ['alnum', 'digits', 'letters', 'hex'];
const CASES: CodeCase[] = ['none', 'upper', 'lower'];
const MODES: GeneratorMode[] = ['default', 'custom', 'legacy'];

const isObj = (v: unknown): v is Record<string, unknown> => !!v && typeof v === 'object' && !Array.isArray(v);

const normalizePart = (raw: unknown): CodePart | null => {
  if (!isObj(raw)) return null;
  switch (raw.type) {
    case 'text': {
      const value = sanitizeSegment(typeof raw.value === 'string' ? raw.value : '', MAX_TEXT_LENGTH);
      return value ? { type: 'text', value } : null;
    }
    case 'timestamp': return { type: 'timestamp' };
    case 'date': {
      const f = raw.format as DateFormat;
      return { type: 'date', format: DATE_FORMATS.includes(f) ? f : 'YYYYMMDD' };
    }
    case 'random': {
      const n = Number(raw.length);
      const length = Number.isFinite(n) ? Math.min(MAX_RANDOM, Math.max(MIN_RANDOM, Math.round(n))) : 6;
      const c = raw.charset as RandomCharset;
      return { type: 'random', length, charset: CHARSET_KEYS.includes(c) ? c : 'alnum' };
    }
    case 'church': case 'service': case 'class':
      return { type: raw.type, fallback: sanitizeSegment(typeof raw.fallback === 'string' ? raw.fallback : '', MAX_ABBREVIATION_LENGTH) };
    default: return null;
  }
};

export const normalizeTemplate = (raw: unknown): CodeTemplate => {
  if (!isObj(raw)) return { parts: [], separator: '-', case: 'none' };
  const parts = (Array.isArray(raw.parts) ? raw.parts : [])
    .map(normalizePart)
    .filter((p): p is CodePart => !!p)
    .slice(0, MAX_PARTS);
  const separator = typeof raw.separator === 'string' ? sanitizeSegment(raw.separator, MAX_SEPARATOR_LENGTH) : '-';
  const c = raw.case as CodeCase;
  return { parts, separator, case: CASES.includes(c) ? c : 'none' };
};

const normalizeAbbrMap = (raw: unknown): Record<string, string> => {
  const out: Record<string, string> = {};
  if (!isObj(raw)) return out;
  for (const [k, v] of Object.entries(raw)) {
    if (typeof v !== 'string') continue;
    const s = sanitizeSegment(v.trim(), MAX_ABBREVIATION_LENGTH);
    if (s) out[k] = s;
  }
  return out;
};

export const normalizeCodes = (raw: unknown): CodesConfig => {
  if (!isObj(raw)) return DEFAULT_CODES;
  const def = normalizeTemplate(raw.default);
  const gensRaw = isObj(raw.generators) ? raw.generators : {};
  const generators = {} as Record<CodeKind, GeneratorConfig>;
  for (const kind of CODE_KINDS) {
    const g = gensRaw[kind];
    if (!isObj(g)) { generators[kind] = { mode: 'legacy' }; continue; }
    const mode = MODES.includes(g.mode as GeneratorMode) ? (g.mode as GeneratorMode) : 'legacy';
    const cfg: GeneratorConfig = { mode };
    if (g.template !== undefined) cfg.template = normalizeTemplate(g.template);
    generators[kind] = cfg;
  }
  const sc = isObj(raw.scopes) ? raw.scopes : {};
  return {
    version: 1,
    default: def.parts.length > 0 ? def : DEFAULT_TEMPLATE,
    generators,
    scopes: {
      churches: normalizeAbbrMap(sc.churches),
      services: normalizeAbbrMap(sc.services),
      classes: normalizeAbbrMap(sc.classes),
    },
  };
};

/** true when at least one generator does NOT use the legacy built-in generator */
export const codesActive = (cfg: CodesConfig): boolean =>
  CODE_KINDS.some((k) => cfg.generators[k]?.mode !== 'legacy');

/** short human summary for the hub */
export const summarizeCodes = (cfg: CodesConfig, customized: boolean): string => {
  if (!customized || !codesActive(cfg)) return 'الطريقة الأصلية لكل الأكواد (P-XXXXXXXX …)';
  const def = previewTemplate(cfg.default);
  const custom = CODE_KINDS.filter((k) => cfg.generators[k]?.mode === 'custom').length;
  const legacy = CODE_KINDS.filter((k) => cfg.generators[k]?.mode === 'legacy').length;
  const extras = [
    custom ? `${custom} تصميم خاص` : '',
    legacy ? `${legacy} بالطريقة الأصلية` : '',
  ].filter(Boolean).join(' · ');
  return `الافتراضي: ${def}${extras ? ` — ${extras}` : ''}`;
};
