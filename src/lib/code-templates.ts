// ---------- parts ----------
export type PartType = 'text' | 'timestamp' | 'date' | 'random' | 'church' | 'service' | 'class';
export type DateFormat = 'YYYYMMDD' | 'YYMMDD' | 'DDMMYYYY' | 'DDMMYY' | 'YYYYMM' | 'YYMM' | 'YYYY' | 'YY';
export type RandomCharset = 'alnum' | 'digits' | 'letters' | 'hex';
export type ScopePartType = 'church' | 'service' | 'class';

export interface TextPart { type: 'text'; value: string }
export interface TimestampPart { type: 'timestamp' }
export interface DatePart { type: 'date'; format: DateFormat }
export interface RandomPart { type: 'random'; length: number; charset: RandomCharset }
export interface ScopePart { type: ScopePartType; fallback: string }
export type CodePart = TextPart | TimestampPart | DatePart | RandomPart | ScopePart;

export type CodeCase = 'none' | 'upper' | 'lower';

export interface CodeTemplate {
  parts: CodePart[];
  /** joined between non-empty parts — '' allowed (no separator) */
  separator: string;
  case: CodeCase;
}

export type GeneratorMode = 'default' | 'custom' | 'legacy';
export interface GeneratorConfig {
  mode: GeneratorMode;
  /** the generator's own template (used when mode = 'custom') */
  template?: CodeTemplate;
}

export interface ScopeAbbreviations {
  churches: Record<string, string>;
  services: Record<string, string>;
  classes: Record<string, string>;
}

export interface CodesConfig {
  version: 1;
  /** the default system followed by every generator in 'default' mode */
  default: CodeTemplate;
  generators: Record<CodeKind, GeneratorConfig>;
  scopes: ScopeAbbreviations;
}

export interface CodeContext {
  churchId?: string | null;
  serviceId?: string | null;
  classId?: string | null;
  /** generation moment (ms) — bulk imports pass a monotonic clock so timestamp codes never collide */
  now?: number;
}

