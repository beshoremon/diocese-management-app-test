const SAMPLE_SCOPES: ScopeAbbreviations = {
  churches: { sample: 'STM' }, services: { sample: 'SS' }, classes: { sample: 'C1' },
};
const SAMPLE_CTX: CodeContext = { churchId: 'sample', serviceId: 'sample', classId: 'sample', now: 1702655732293 };

/** Deterministic preview (fixed moment + sample abbreviations) for the editor. */
export const previewTemplate = (t: CodeTemplate, opts?: { scopes?: ScopeAbbreviations; ctx?: CodeContext }): string => {
  const scopes = opts?.scopes ?? SAMPLE_SCOPES;
  const ctx = { ...SAMPLE_CTX, ...(opts?.ctx ?? {}) };
  const segs = t.parts.map((p) => {
    if (p.type === 'random') {
      // stable-looking sample instead of noise
      const alphabet = CHARSETS[p.charset] ?? ALNUM;
      let s = '';
      for (let i = 0; i < p.length; i++) s += alphabet[(i * 7 + 3) % alphabet.length];
      return s;
    }
    return renderPart(p, ctx, scopes);
  }).filter((s) => s.length > 0);
  return applyCase(segs.join(t.separator), t.case);
};

