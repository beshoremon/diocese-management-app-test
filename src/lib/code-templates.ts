// ---------- legacy (built-in) generators ----------
const ALNUM = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
const CHARSETS: Record<RandomCharset, string> = {
  alnum: ALNUM,
  digits: '0123456789',
  letters: 'ABCDEFGHJKLMNPQRSTUVWXYZ',
  hex: '0123456789ABCDEF',
};

const randomChars = (n: number, charset: RandomCharset): string => {
  const alphabet = CHARSETS[charset] ?? ALNUM;
  let s = '';
  for (let i = 0; i < n; i++) s += alphabet[Math.floor(Math.random() * alphabet.length)];
  return s;
};

/** what the app produced before the code system existed */
export const legacyCode = (kind: CodeKind): string => {
  switch (kind) {
    case 'store_item': return `ST-${randomChars(6, 'alnum')}`;
    case 'ticket': return `T-${randomChars(10, 'hex')}`;
    case 'family': return `F-${randomChars(6, 'alnum')}`;
    default: return `P-${randomChars(8, 'alnum')}`;
  }
};

// ---------- rendering ----------
const pad2 = (n: number) => String(n).padStart(2, '0');

export const formatDate = (d: Date, format: DateFormat): string => {
  const yyyy = String(d.getFullYear());
  const yy = yyyy.slice(2);
  const mm = pad2(d.getMonth() + 1);
  const dd = pad2(d.getDate());
  switch (format) {
    case 'YYYYMMDD': return `${yyyy}${mm}${dd}`;
    case 'YYMMDD': return `${yy}${mm}${dd}`;
    case 'DDMMYYYY': return `${dd}${mm}${yyyy}`;
    case 'DDMMYY': return `${dd}${mm}${yy}`;
    case 'YYYYMM': return `${yyyy}${mm}`;
    case 'YYMM': return `${yy}${mm}`;
    case 'YYYY': return yyyy;
    case 'YY': return yy;
    default: return `${yyyy}${mm}${dd}`;
  }
};

const scopeAbbreviation = (part: ScopePart, ctx: CodeContext, scopes: ScopeAbbreviations): string => {
  const id = part.type === 'church' ? ctx.churchId : part.type === 'service' ? ctx.serviceId : ctx.classId;
  const map = part.type === 'church' ? scopes.churches : part.type === 'service' ? scopes.services : scopes.classes;
  const abbr = id ? map[id] : undefined;
  return (abbr && abbr.trim()) || part.fallback || '';
};

/** Render ONE part — '' means "skip" (no separator is emitted for it). */
export const renderPart = (part: CodePart, ctx: CodeContext, scopes: ScopeAbbreviations): string => {
  switch (part.type) {
    case 'text': return part.value;
    case 'timestamp': return String(ctx.now ?? Date.now());
    case 'date': return formatDate(new Date(ctx.now ?? Date.now()), part.format);
    case 'random': return randomChars(part.length, part.charset);
    default: return scopeAbbreviation(part, ctx, scopes);
  }
};

export const applyCase = (s: string, c: CodeCase): string =>
  c === 'upper' ? s.toUpperCase() : c === 'lower' ? s.toLowerCase() : s;

/** Render a full template — empty parts are dropped so no double separators appear. */
export const renderTemplate = (t: CodeTemplate, ctx: CodeContext = {}, scopes: ScopeAbbreviations = EMPTY_SCOPES): string => {
  const segs = t.parts.map((p) => renderPart(p, ctx, scopes)).filter((s) => s.length > 0);
  return applyCase(segs.join(t.separator), t.case);
};

/** The template a generator actually uses — null = legacy built-in generator. */
export const resolveTemplate = (cfg: CodesConfig | null | undefined, kind: CodeKind): CodeTemplate | null => {
  if (!cfg) return null;
  const g = cfg.generators[kind] ?? { mode: 'legacy' };
  if (g.mode === 'legacy') return null;
  if (g.mode === 'custom' && g.template && g.template.parts.length > 0) return g.template;
  return cfg.default.parts.length > 0 ? cfg.default : null;
};

/** Generate a code for `kind` using the owner's configuration (legacy when unset). */
export const generateCode = (cfg: CodesConfig | null | undefined, kind: CodeKind, ctx: CodeContext = {}): string => {
  const t = resolveTemplate(cfg, kind);
  if (!t) return legacyCode(kind);
  const out = renderTemplate(t, ctx, cfg!.scopes);
  return out || legacyCode(kind);
};

/**
 * A monotonic clock for bulk generation: each call returns a millisecond value
 * strictly greater than the previous one so timestamp-based codes stay unique
 * even when hundreds of rows are generated inside one millisecond.
 */
export const monotonicClock = () => {
  let last = 0;
  return () => {
    const now = Date.now();
    last = now > last ? now : last + 1;
    return last;
  };
};

