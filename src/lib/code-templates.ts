// ---------- factories ----------
export const newPart = (type: PartType): CodePart => {
  switch (type) {
    case 'text': return { type, value: 'P' };
    case 'timestamp': return { type };
    case 'date': return { type, format: 'YYYYMMDD' };
    case 'random': return { type, length: 6, charset: 'alnum' };
    default: return { type, fallback: '' };
  }
};

export const text = (value: string): TextPart => ({ type: 'text', value });
export const timestamp = (): TimestampPart => ({ type: 'timestamp' });
export const date = (format: DateFormat = 'YYYYMMDD'): DatePart => ({ type: 'date', format });
export const random = (length = 6, charset: RandomCharset = 'alnum'): RandomPart => ({ type: 'random', length, charset });
export const scope = (type: ScopePartType, fallback = ''): ScopePart => ({ type, fallback });

export const template = (parts: CodePart[], separator = '-', kase: CodeCase = 'none'): CodeTemplate =>
  ({ parts, separator, case: kase });

