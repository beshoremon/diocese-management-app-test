/** allowed in every literal segment — keeps the code a valid login name too */
export const SAFE_SEGMENT_RE = /^[A-Za-z0-9._-]*$/;
export const sanitizeSegment = (s: string, max: number): string =>
  s.replace(/[^A-Za-z0-9._-]/g, '').slice(0, max);

