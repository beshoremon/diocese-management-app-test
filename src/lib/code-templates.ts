// ---------- CODE SYSTEM (تخصيص التطبيق → نظام الأكواد) ----------
// The owner designs HOW the app builds the codes it generates: a code is a
// TEMPLATE = ordered PARTS joined by a SEPARATOR (dash by default), e.g.
//
//   [text "P"] - [timestamp]                →  P-1702655732293
//   [church] - [class] - [date YYMMDD] - [random 4]  →  STM-C1-231215-4F7K
//
// Part types:
//   text       fixed literal (prefix / suffix)
//   timestamp  the moment of generation in milliseconds  → 1702655732293
//   date       formatted generation date (YYYYMMDD · YYMMDD · YYYY …)
//   random     N random characters (letters+digits · digits · letters · hex)
//   church / service / class  the ABBREVIATION the owner gave that scope
//              (تخصيص الأكواد → اختصارات الكنائس والخدمات والفصول), with a
//              fallback text when the scope has none / isn't selected.
//
// One DEFAULT SYSTEM is shared by every generator; each GENERATOR in the app
// (كود المخدوم · كود الخادم · كود منتج المتجر · كود تذكرة المناسبة) may:
//   'default' → follow the default system
//   'custom'  → have its own template
//   'legacy'  → keep the app's original built-in generator (P-XXXXXXXX …)
//
// Stored in `app_settings.key = 'codes'` (migration 0040, owner-write /
// all-read / realtime; anonymous signup reads it through `code_settings()`).
// `public.render_code()` in SQL mirrors `renderTemplate()` below so codes
// generated by the database (occasion tickets) follow the same design.
// Codes must stay within [A-Za-z0-9._-] — a servant's code is also his login
// name (see `code_to_user_id`).

